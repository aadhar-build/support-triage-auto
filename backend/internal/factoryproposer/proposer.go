// Package factoryproposer asks a native provider CLI for one factory scheduling decision.
package factoryproposer

import (
	"context"
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"regexp"
	"time"

	"github.com/aadhar-build/support-triage-auto/backend/internal/factorycontroller"
)

const (
	defaultTimeout = 90 * time.Second
	maxQueueSize   = 512
)

var (
	ErrNoDecision = errors.New("no scheduling provider returned a valid factory decision")
	modelID       = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_.:@+\-]{0,127}$`)
)

// Config names trusted native executables chosen by the operator. Use absolute
// paths from outside any job checkout. The adapter never resolves binaries from PATH.
// Provision separate private homes with the provider's credentials and only
// runtime state generated by the trusted native CLI, including model caches.
// Native login uses ClaudeHome/.claude and CodexHome/.codex respectively.
// Deploy on a trusted host where managed policy and plugins cannot introduce hooks
// or tools into the scheduling profiles.
// A zero AttemptTimeout gives each auth and model invocation pair 90 seconds.
type Config struct {
	ClaudeBinary      string
	ClaudeModel       string
	ClaudeHome        string
	ClaudeUnavailable bool
	CodexBinary       string
	CodexModel        string
	CodexHome         string
	CodexUnavailable  bool
	AttemptTimeout    time.Duration
}

type Disposition string

const (
	Accepted       Disposition = "accepted"
	Unavailable    Disposition = "unavailable"
	AuthFailed     Disposition = "required-login-not-verified"
	UnsafeProfile  Disposition = "unsafe-profile"
	Failed         Disposition = "cli-failed"
	Invalid        Disposition = "invalid-decision"
	TimedOut       Disposition = "timed-out"
	OutputTooLarge Disposition = "output-too-large"
	Canceled       Disposition = "canceled"
)

type Phase string

const (
	PhaseSetup    Phase = "setup"
	PhaseLogin    Phase = "login"
	PhaseModel    Phase = "model"
	PhaseDecision Phase = "decision"
)

type Failure string

const (
	FailureRunner     Failure = "runner"
	FailureNativeExit Failure = "native-exit"
	FailureCLIArgs    Failure = "cli-arguments"
	FailureCLIConfig  Failure = "cli-configuration"
	FailureAuth       Failure = "authentication"
	FailureNetwork    Failure = "network"
	FailureModel      Failure = "model-unavailable"
)

// Attempt describes a provider outcome without including prompts, output or credentials.
// The ordered attempts also show when and why scheduling reached the fallback provider.
type Attempt struct {
	Provider    string      `json:"provider"`
	Model       string      `json:"model"`
	Disposition Disposition `json:"disposition"`
	Phase       Phase       `json:"phase"`
	Failure     Failure     `json:"failure,omitempty"`
	Rejection   string      `json:"rejection,omitempty"`
}

type Proposer struct {
	claude, codex cli
	timeout       time.Duration
}

var _ factorycontroller.Proposer = (*Proposer)(nil)

func New(cfg Config) (*Proposer, error) {
	if !filepath.IsAbs(cfg.ClaudeBinary) || !filepath.IsAbs(cfg.CodexBinary) {
		return nil, errors.New("scheduling CLIs require absolute executable paths")
	}
	if !modelID.MatchString(cfg.ClaudeModel) || !modelID.MatchString(cfg.CodexModel) {
		return nil, errors.New("scheduling requires valid Claude and Codex model names")
	}
	claudeHome, codexHome := privateHome(cfg.ClaudeHome), privateHome(cfg.CodexHome)
	if claudeHome == "" || codexHome == "" || contains(claudeHome, codexHome) || contains(codexHome, claudeHome) {
		return nil, errors.New("scheduling requires separate private Claude and Codex homes")
	}
	if cfg.AttemptTimeout < 0 || cfg.AttemptTimeout > 5*time.Minute {
		return nil, errors.New("scheduling attempt timeout must be at most five minutes")
	}
	if cfg.AttemptTimeout == 0 {
		cfg.AttemptTimeout = defaultTimeout
	}
	return &Proposer{
		claude:  cli{"claude", cfg.ClaudeBinary, cfg.ClaudeModel, claudeHome, cfg.ClaudeUnavailable},
		codex:   cli{"codex", cfg.CodexBinary, cfg.CodexModel, codexHome, cfg.CodexUnavailable},
		timeout: cfg.AttemptTimeout,
	}, nil
}

func privateHome(path string) string {
	if !filepath.IsAbs(path) {
		return ""
	}
	info, err := os.Lstat(filepath.Clean(path))
	if err != nil || !info.IsDir() || !controlledByUser(info) || info.Mode().Perm()&0077 != 0 {
		return ""
	}
	resolved, err := filepath.EvalSymlinks(path)
	if err != nil {
		return ""
	}
	ambient, _ := os.UserHomeDir()
	ambient, _ = filepath.EvalSymlinks(ambient)
	if resolved == ambient {
		return ""
	}
	return resolved
}

func contains(root, path string) bool {
	relative, err := filepath.Rel(root, path)
	return err == nil && filepath.IsLocal(relative)
}

func (p *Proposer) Propose(ctx context.Context, snapshot factorycontroller.Snapshot) (factorycontroller.Proposal, error) {
	proposal, _, err := p.ProposeWithReport(ctx, snapshot)
	return proposal, err
}

// ProposeWithReport tries Claude first. An invalid decision gets one
// reconsideration with the deterministic rejection before switching to Codex.
// Unavailable or failed invocations move directly to the configured fallback.
func (p *Proposer) ProposeWithReport(ctx context.Context, snapshot factorycontroller.Snapshot) (factorycontroller.Proposal, []Attempt, error) {
	if err := ctx.Err(); err != nil {
		return factorycontroller.Proposal{}, nil, err
	}
	prompt, err := createPrompt(snapshot)
	if err != nil {
		return factorycontroller.Proposal{}, nil, err
	}

	var attempts []Attempt
	rejection := ""
	for _, provider := range []cli{p.claude, p.claude, p.codex} {
		if len(attempts) == 1 && attempts[0].Disposition != Invalid && provider.name == "claude" {
			continue
		}
		if err := ctx.Err(); err != nil {
			return factorycontroller.Proposal{}, attempts, err
		}
		proposal, attempt := p.attempt(ctx, provider, prompt, rejection, snapshot)
		attempts = append(attempts, attempt)
		if err := ctx.Err(); err != nil {
			return factorycontroller.Proposal{}, attempts, err
		}
		if attempt.Disposition == Accepted {
			return proposal, attempts, nil
		}
		rejection = attempt.Rejection
	}
	return factorycontroller.Proposal{}, attempts, ErrNoDecision
}

func (p *Proposer) attempt(ctx context.Context, provider cli, prompt, rejection string, snapshot factorycontroller.Snapshot) (factorycontroller.Proposal, Attempt) {
	ctx, cancel := context.WithTimeout(ctx, p.timeout)
	defer cancel()
	if rejection != "" {
		prompt += "\nThe previous proposal was rejected. Select again using this validation result: " + rejection
	}
	result, attempt := provider.run(ctx, prompt)
	if attempt.Disposition != Accepted {
		if attempt.Disposition == Invalid {
			attempt.Rejection = "provider did not return a complete decision"
		}
		return factorycontroller.Proposal{}, attempt
	}
	proposal, err := resolveDecision(result, snapshot)
	if err != nil {
		attempt.Disposition = Invalid
		attempt.Rejection = err.Error()
		return factorycontroller.Proposal{}, attempt
	}
	return proposal, attempt
}

type candidate struct {
	Number   int  `json:"candidate"`
	Eligible bool `json:"eligible"`
	Round    int  `json:"current_round"`
}

func createPrompt(snapshot factorycontroller.Snapshot) (string, error) {
	if len(snapshot.Jobs) > maxQueueSize {
		return "", errors.New("scheduling snapshot exceeds candidate limit")
	}
	if _, err := factorycontroller.Validate(snapshot, factorycontroller.Proposal{
		Action: factorycontroller.ActionNoAction, StateRevision: snapshot.Revision,
	}); err != nil {
		return "", err
	}
	view := struct {
		ActiveBuilds  int         `json:"active_builds"`
		BuildCapacity int         `json:"build_capacity"`
		Candidates    []candidate `json:"candidates"`
	}{snapshot.ActiveBuilds, snapshot.BuildCapacity, make([]candidate, 0, len(snapshot.Jobs))}
	for index, job := range snapshot.Jobs {
		_, err := factorycontroller.Validate(snapshot, pickup(snapshot, job))
		if errors.Is(err, factorycontroller.ErrInvalidSnapshot) {
			return "", err
		}
		view.Candidates = append(view.Candidates, candidate{Number: index + 1, Eligible: err == nil, Round: job.Round})
	}
	input, err := json.Marshal(view)
	if err != nil {
		return "", errors.New("could not encode scheduling candidates")
	}
	return `Select a build pickup from the supplied scheduling snapshot, or choose no action.
Use only the listed candidates and choose only a candidate marked eligible. The input has no cost, priority, or deadline estimates.
Return exactly one JSON object with no other text. For a pickup use {"action":"pickup-build","candidate":2}, substituting the candidate's number.
For no action use {"action":"no-action"}.
Scheduling snapshot:
` + string(input), nil
}

func resolveDecision(result string, snapshot factorycontroller.Snapshot) (factorycontroller.Proposal, error) {
	reject := func() (factorycontroller.Proposal, error) {
		return factorycontroller.Proposal{}, errors.New("return one no-action or pickup-build JSON object with the required fields")
	}
	object := jsonObject([]byte(result))
	var proposal factorycontroller.Proposal
	switch jsonText(object["action"]) {
	case string(factorycontroller.ActionNoAction):
		if len(object) != 1 {
			return reject()
		}
		proposal = factorycontroller.Proposal{Action: factorycontroller.ActionNoAction, StateRevision: snapshot.Revision}
	case string(factorycontroller.ActionPickupBuild):
		var number int
		if len(object) != 2 || json.Unmarshal(object["candidate"], &number) != nil {
			return reject()
		}
		if number < 1 || number > len(snapshot.Jobs) {
			return factorycontroller.Proposal{}, errors.New("candidate is not in this snapshot")
		}
		proposal = pickup(snapshot, snapshot.Jobs[number-1])
	default:
		return reject()
	}
	if _, err := factorycontroller.Validate(snapshot, proposal); err != nil {
		return factorycontroller.Proposal{}, err
	}
	return proposal, nil
}

func pickup(snapshot factorycontroller.Snapshot, job factorycontroller.Job) factorycontroller.Proposal {
	return factorycontroller.Proposal{
		Action: factorycontroller.ActionPickupBuild, StateRevision: snapshot.Revision,
		JobID: job.ID, JobRevision: job.Revision,
	}
}
